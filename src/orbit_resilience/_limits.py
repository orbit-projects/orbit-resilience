"""Finite-number and capacity rules owned by the optional resilience package."""

import math
from typing import TypeGuard

MAX_RESILIENCE_CAPACITY = 1_000_000


def is_finite_number(value: object) -> TypeGuard[int | float]:
    """Accept finite non-boolean numbers while treating integer overflow as invalid input."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return False
    try:
        return math.isfinite(value)
    except OverflowError:
        return False
